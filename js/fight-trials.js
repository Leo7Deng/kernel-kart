// Fight's combo trials: for every fighter, three or four strings to learn in the training room, built on the kits as they are
// (js/kits/<id>.js) and on what the kit audit measured links (a setup, then its payoff). Plain data, DOM-free:
// js/fight-practice.js checks them from the fight's events, js/fight-practice-ui.js shows them (the Trials tab), and
// test/fight-practice.test.mjs plays every demo and checks it completes its own trial.
//   a trial   { k (unique, saved with the checklist's ticks), name, how (one line: what to do), mode (the dummy's, while
//             it's picked), steps, demo }
//   a step    { m (the move it shows: move1..3 or evade, its key and icon), what (the line shown), ev (the event kind that
//             does it), by (whose event: 0 you, 1 the dummy; default 0), ok(e, F, got) (a check on it: false is a near
//             miss, the attempt breaks there; got: the events of the steps done so far), gap (s it may come after the
//             step before, default the trial's gap or GAP), miss (an event kind of yours that's this step missing:
//             it breaks the attempt), auto (1: it follows by itself, no key to press: shown without one), tip (the hint when the attempt breaks at this step) }
//             An event with `to` must be to the dummy (1). A 'whiff' of the step's move breaks the attempt too.
//   a demo    a scripted clip (js/fight-clips.js's format, run in a practice fight: fight-practice.js trialDemo): { x, y?
//             (where the two stand), len (s), cam ({ x, y?, w }), a (your inputs: [from, to, input]), b (the dummy's) }.
//             The dummy is DEMO_VS(id) on DEMO_ARENA; mode: it does what that mode does instead of b (seeded: the same
//             every time; seed: its stream).
// The attempt (fight-practice.js): step 1 starts it; each next step must come in order, within its gap; a near miss, a
// whiff or the gap running out breaks it, and the step it broke at gives the hint. Step 1 again starts it over.
